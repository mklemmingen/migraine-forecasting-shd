"""Project-wide training-time stdout/stderr capture.

Provides ``capture_training_output(leaf_dir, label='training')`` as a
context manager that tees ``sys.stdout`` and ``sys.stderr`` to a
per-leaf log file under ``<leaf_dir>/_running_output/``. The terminal
still receives the original output (live progress preserved) while the
file accumulates the full record for post-hoc audit.

Used by every train.py and evaluate.py generated by
``experiment/<n>/_scaffold_leaves.py`` so that any library messages
(TabPFN finetuning progress, AutoGluon ensemble decisions, sklearn
deprecations, ROCm runtime diagnostics, etc.) become persistent
artifacts of each run rather than ephemeral terminal output.

Coverage of library output mechanisms:

  - ``print()`` calls - captured (via sys.stdout redirect).
  - ``tqdm`` progress bars - captured (writes to sys.stderr).
  - Python ``logging.StreamHandler`` with default ``sys.stderr`` -
    captured.
  - AutoGluon ``TabularPredictor`` verbose output (logging-based) -
    captured.
  - TabPFN finetuning per-epoch messages (tqdm-based) - captured.

  Not captured:
  - Library output that bypasses the Python streams via direct
    ``os.write(1, ...)`` (rare).
  - Subprocess output spawned by a library (those subprocesses inherit
    the parent's file descriptors but their write goes to the original
    terminal, not the tee - uncommon in this project's stack).
"""

from __future__ import annotations

import sys
import uuid
from contextlib import contextmanager
from datetime import datetime
from pathlib import Path
from typing import Iterator, TextIO


class _Tee:
    """Stream-like object that writes to multiple targets and flushes
    eagerly so partial output survives a crash mid-run."""

    def __init__(self, *targets: TextIO) -> None:
        self._targets = targets

    def write(self, data: str) -> int:
        for t in self._targets:
            try:
                t.write(data)
                t.flush()
            except (ValueError, OSError):
                # A target may be closed by the time of write (e.g. after
                # the context manager exits during interpreter shutdown).
                # Silently skip - best-effort tee, never raise.
                pass
        return len(data)

    def flush(self) -> None:
        for t in self._targets:
            try:
                t.flush()
            except (ValueError, OSError):
                pass

    def isatty(self) -> bool:
        # tqdm and similar consult isatty() to decide on progress-bar
        # rendering. Forward the original stream's tty-ness so the
        # terminal still gets a live progress bar rather than an
        # exploded line-by-line dump.
        for t in self._targets:
            try:
                if t.isatty():
                    return True
            except (ValueError, OSError, AttributeError):
                continue
        return False

    @property
    def encoding(self) -> str:
        for t in self._targets:
            enc = getattr(t, 'encoding', None)
            if enc:
                return enc
        return 'utf-8'

    def fileno(self) -> int:
        # Some libraries call fileno() to get the underlying fd.
        # Return the original (first) target's fd so those code paths
        # still write to the terminal - they bypass the tee, but the
        # alternative (raising) would break those libraries entirely.
        for t in self._targets:
            try:
                return t.fileno()
            except (ValueError, OSError, AttributeError):
                continue
        raise OSError('Tee has no target with a fileno')


@contextmanager
def capture_training_output(
    leaf_dir: str | Path,
    label: str = 'training',
) -> Iterator[Path]:
    """Tee stdout/stderr to ``<leaf_dir>/_running_output/<label>_<ts>_<uuid>.txt``.

    Args:
        leaf_dir: directory of the calling leaf (typically EXPERIMENT_DIR
            in the train.py/evaluate.py templates).
        label: prefix for the log filename. Defaults to ``'training'``;
            evaluate-time use should pass ``label='evaluation'``.

    Yields:
        The :class:`pathlib.Path` to the freshly-opened log file.

    The log file is created with a metadata header (timestamp, UUID,
    leaf path) followed by everything written to ``sys.stdout`` /
    ``sys.stderr`` during the context. The original streams are
    restored on exit.
    """
    leaf_dir = Path(leaf_dir)
    out_dir = leaf_dir / '_running_output'
    out_dir.mkdir(exist_ok=True)
    ts = datetime.now().strftime('%Y%m%d_%H%M%S_%f')[:-3]
    uid = str(uuid.uuid4())
    log_path = out_dir / f'{label}_{ts}_{uid}.txt'

    original_stdout = sys.stdout
    original_stderr = sys.stderr
    logfile = open(log_path, 'w', buffering=1, encoding='utf-8')

    try:
        logfile.write(f'# Training-script output capture\n')
        logfile.write(f'# Generated: {datetime.now().isoformat(timespec="seconds")}\n')
        logfile.write(f'# UUID:      {uid}\n')
        logfile.write(f'# Label:     {label}\n')
        logfile.write(f'# Leaf:      {leaf_dir}\n')
        logfile.write(f'# Captures stdout/stderr written during the wrapped block\n')
        logfile.write(f'# (library messages, warnings, progress bars, etc.).\n')
        logfile.write(f'# Begin capture ----------------------------------------\n')
        logfile.flush()

        sys.stdout = _Tee(original_stdout, logfile)
        sys.stderr = _Tee(original_stderr, logfile)

        yield log_path
    finally:
        sys.stdout = original_stdout
        sys.stderr = original_stderr
        try:
            logfile.write(f'\n# End capture ------------------------------------------\n')
            logfile.write(f'# Finished: {datetime.now().isoformat(timespec="seconds")}\n')
            logfile.flush()
        finally:
            logfile.close()
